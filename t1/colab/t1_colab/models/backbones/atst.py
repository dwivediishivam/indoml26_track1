"""ATST-Frame, AudioSet-Strong fine-tuned (PretrainedSED release ATST-F_strong_1.pt).

Frontend == vendored ATSTMel (torchaudio MelSpectrogram 16 kHz, n_fft=win=1024, hop 160, 64 mels 60-7800 Hz,
center=True; AmplitudeToDB(power, top_db=80); clamp[-50, 80]; fixed MinMax(-79.6482, 50.6842) -> [-1, 1]).
Only difference (topdb="sample", default): the top_db floor is computed per clip over its valid frames
instead of over the whole batch (upstream torchaudio AmplitudeToDB on a [B, F, T] tensor takes one max
across the batch, which makes features depend on batch composition). topdb="batch" restores upstream.

Tokens: patch 64 mels x 4 frames -> one token per 40 ms; token k covers mel frames 4k..4k+3 whose
centres are 10 ms * (4k..4k+3) -> token centre 0.04 k + 0.015 s. Absolute ("cut") positional
embeddings allow <= 250 tokens = 10 s, so longer inputs are split into 10 s windows (start on a 40 ms
grid, >= `min_overlap_sec` overlap, trapezoid overlap-add). Self-attention gets a key-padding mask so
padded tokens never influence valid ones (the vendored Block ignores lengths, so the blocks are driven here).
"""
from __future__ import annotations

import math

import torch
import torch.nn.functional as F
from torch import Tensor, nn
from torch.utils.checkpoint import checkpoint as _ckpt

from .base import (Backbone, LayerMix, chunked_encode, group_params_by_layer, n_out_frames, prepare_lengths,
                   resample_to_frames, resolve_file)
from .vendor.atst.wrapper import ATSTWrapper

ATST_FILES = ["ATST-F_strong_1.pt"]
WIN = 160000            # 10 s -> 1001 mel frames -> 250 tokens
TOKEN_HOP = 640         # samples (40 ms)
TOKEN_FIRST_CENTER = 0.015


def load_atst_strong(encoder: ATSTWrapper, checkpoint) -> None:
    """Exactly the Phase-2 recovery loader: PredictionsWrapper(ATSTWrapper) state with AudioSet heads."""
    state = torch.load(checkpoint, map_location="cpu", weights_only=True)
    unexpected = [k for k in state if not k.startswith(("model.", "strong_head.", "weak_head."))]
    if unexpected:
        raise ValueError(f"Unexpected pretrained keys: {unexpected[:5]}")
    encoder_state = {k[len("model."):]: v for k, v in state.items() if k.startswith("model.")}
    missing, extra = encoder.load_state_dict(encoder_state, strict=False)
    # Frontend buffers are deterministically generated by the author's frontend.
    if extra or any(not k.startswith("atst_mel.mel_transform.") for k in missing):
        raise ValueError(f"ATST load mismatch: missing={missing}, extra={extra}")


class ATSTStrong(Backbone):
    """kwargs: checkpoint=None (auto-search), layer_mix=False, per_layer_norm=True, dropout=0.0,
    topdb="sample"|"batch", min_overlap_sec=2.0, grad_ckpt=False, pretrained=True."""

    def __init__(self, checkpoint=None, layer_mix: bool = False, per_layer_norm: bool = True, dropout: float = 0.0,
                 topdb: str = "sample", min_overlap_sec: float = 2.0, grad_ckpt: bool = False,
                 pretrained: bool = True):
        super().__init__()
        self.encoder = ATSTWrapper(atst_dropout=dropout)
        if pretrained:
            path = resolve_file(checkpoint, ATST_FILES, env_var="ATST_STRONG_CKPT")
            load_atst_strong(self.encoder, path)
            self.checkpoint = str(path)
        self._mark_unused(self.atst.mask_embed)          # only used for SSL masking
        if topdb not in ("sample", "batch"):
            raise ValueError("topdb must be 'sample' or 'batch'")
        self.topdb = topdb
        self.min_overlap = int(round(min_overlap_sec * 16000 / TOKEN_HOP)) * TOKEN_HOP
        self.grad_ckpt = grad_ckpt
        self.n_blocks = len(self.atst.blocks)
        self.mix = LayerMix(self.n_blocks + 1, 768, per_layer_norm) if layer_mix else None
        self.out_dim = 768

    @property
    def atst(self):                                       # FrameAST (not re-registered as a submodule)
        return self.encoder.atst

    def encoder_modules(self):
        return [self.encoder]

    # ---------------------------------------------------------------- frontend
    def _spec(self, wav: Tensor, lengths: Tensor) -> Tensor:
        mel = self.encoder.atst_mel
        if self.topdb == "batch":
            return mel(wav.float())
        with torch.autocast(device_type=wav.device.type, enabled=False):
            spec = mel.mel_transform(wav.float())                               # [B, 64, M]
            db = 10.0 * torch.log10(spec.clamp(min=1e-10))                       # AmplitudeToDB(power), ref=1
            M = db.shape[-1]
            valid = (lengths // 160 + 1).clamp(1, M)
            vmask = torch.arange(M, device=db.device)[None, :] < valid[:, None]
            peak = db.masked_fill(~vmask[:, None, :], -1e4).amax(dim=(1, 2), keepdim=True)
            db = torch.maximum(db, peak - 80.0).clamp(min=-50, max=80)
            spec = mel.scaler(db)
        return spec.unsqueeze(1)                                                 # [B, 1, 64, M]

    # ---------------------------------------------------------------- encoder (<= 10 s)
    def _block(self, blk, x, bias):
        y, _ = blk.attn(blk.norm1(x), bias)
        x = x + blk.drop_path(y)
        return x + blk.drop_path(blk.mlp(blk.norm2(x)))

    def _encode(self, wav: Tensor, lengths: Tensor):
        spec = self._spec(wav, lengths)
        x, *_ = self.atst.prepare_tokens(spec, mask_index=None, length=None, mask=False)   # [B, L, 768]
        B, L, _ = x.shape
        if L > self.atst.pos_embed.shape[1] - 1:
            raise RuntimeError(f"ATST got {L} tokens (> 10 s); chunking failed")
        mel_valid = lengths // 160 + 1
        valid = torch.div(mel_valid + 3, 4, rounding_mode="floor").clamp(1, L)          # ceil(M_valid / 4)
        pad = torch.arange(L, device=x.device)[None, :] >= valid[:, None]
        bias = torch.zeros(B, 1, 1, L, device=x.device, dtype=torch.float32).masked_fill(pad[:, None, None, :], -1e4)
        hidden = [x] if self.mix is not None else None
        for i, blk in enumerate(self.atst.blocks):
            if self.grad_ckpt and self.training and torch.is_grad_enabled():
                x = _ckpt(self._block, blk, x, bias, use_reentrant=False)
            else:
                x = self._block(blk, x, bias)
            if hidden is not None and i < self.n_blocks - 1:
                hidden.append(x)
        x = self.atst.norm_frame(x)
        if hidden is not None:
            hidden.append(x)
            x = self.mix(hidden)
        return x, valid

    def forward(self, wav: Tensor, lengths: Tensor | None = None) -> Tensor:
        lengths = prepare_lengths(wav, lengths)
        T = n_out_frames(wav.shape[-1])
        if wav.shape[-1] < 2 * TOKEN_HOP:                      # need >= 4 mel frames for one token
            wav = F.pad(wav, (0, 2 * TOKEN_HOP - wav.shape[-1]))
        feats, valid = chunked_encode(self._encode, wav.float(), lengths, WIN, self.min_overlap, TOKEN_HOP)
        return resample_to_frames(feats, T, TOKEN_HOP / 16000, TOKEN_FIRST_CENTER, valid)

    def layer_groups(self):
        """12 groups shallow->deep: [embeddings + block 0], block 1, ..., [block 11 + norm_frame]."""
        def layer_of(name):
            if ".blocks." in name:
                return int(name.split(".blocks.")[1].split(".")[0])
            if "norm_frame" in name:
                return self.n_blocks - 1
            return 0
        return group_params_by_layer(self.encoder.named_parameters(), self.n_blocks, layer_of, self._unused_ids())
